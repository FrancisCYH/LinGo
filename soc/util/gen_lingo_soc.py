#!/usr/bin/env python3
"""Generate the SoC-side collateral from the LinGo hardware spec.

Inputs (synced by util/sync_rtl.sh):
    spec/lingo_spec.json     resolved hardware spec (bus widths, SPM layout)
    spec/axilite_spec.json   CSR register map

Outputs (never edit by hand):
    src/lingo_soc_pkg.sv     SystemVerilog localparams (widths, sizes, SoC map)
    sw/include/lingo_regs.h  C register offsets and base addresses

The SoC address map constants below are the integration contract; the same
values are used by cheshire_top_lingo_pkg.sv (via lingo_soc_pkg) and the
bare-metal drivers (via lingo_regs.h).
"""

import json
import sys
from pathlib import Path

SOC_DIR = Path(__file__).resolve().parent.parent

# Integration contract: Cheshire address map appended on top of DefaultCfg.
SOC_SPM_CACHED_BASE = 0x2000_0000    # CIE region: cacheable, idempotent
SOC_SPM_UNCACHED_BASE = 0x4000_0000  # uncached alias for driver access
SOC_CSR_BASE = 0x4300_0000           # RegBus external slave
SOC_CSR_REGION_BYTES = 1024

HEADER_SV = """// GENERATED by util/gen_lingo_soc.py from spec/*.json -- do not edit.
//
// SoC-side parameters of the LinGo CGRA integration. Hand-written code
// (lingo_wrap, cheshire_top_lingo_pkg) references these instead of literals,
// so regenerating the LinGo hardware only requires re-running
// util/sync_rtl.sh and util/gen_lingo_soc.py.
"""

HEADER_C = """/* GENERATED by util/gen_lingo_soc.py from spec/ JSON files -- do not edit. */"""


def pow2_ceil(n: int) -> int:
    return 1 << (n - 1).bit_length()


def main() -> int:
    spec = json.loads((SOC_DIR / "spec/lingo_spec.json").read_text())
    axil = json.loads((SOC_DIR / "spec/axilite_spec.json").read_text())

    data_width = int(spec["spad_data_width"])
    id_width = int(spec["id_width"])
    axi_addr_width = int(spec["axi_addr_width"])
    axil_addr_width = int(axil["axilite_addr_bit_width"])
    n_banks = int(spec["fgra_iob_num_sides"]) * int(spec["fgra_num_colum"])
    bank_bytes = 1 << int(spec["spad_bank_lg_size"])
    cfg_bytes = 1 << int(spec["spad_cfg_lg_size"])
    spad_bytes = n_banks * bank_bytes
    spm_bytes = spad_bytes + cfg_bytes
    cfg_base = int(axil["cfgmem_baseaddr"])
    tile_num = int(axil["tile_num"])
    spm_region = pow2_ceil(spm_bytes)

    if cfg_base != spad_bytes:
        print(f"warning: cfgmem_baseaddr 0x{cfg_base:x} != data SPM size "
              f"0x{spad_bytes:x}", file=sys.stderr)
    if spm_bytes > (1 << axi_addr_width):
        print("error: SPM does not fit the AXI address width", file=sys.stderr)
        return 1

    # Register map: every reg_* key with a hex-string value, sorted by offset.
    regs = sorted(
        ((k, int(v, 16)) for k, v in axil.items()
         if k.startswith("reg_") and isinstance(v, str) and v.startswith("0x")),
        key=lambda kv: kv[1],
    )

    sv = [HEADER_SV, "package lingo_soc_pkg;",
          "  // --- derived from the LinGo hardware spec ---"]
    sv.append(f"  localparam int unsigned LingoAxiDataWidth  = {data_width};")
    sv.append(f"  localparam int unsigned LingoAxiIdWidth    = {id_width};")
    sv.append(f"  localparam int unsigned LingoAxiAddrWidth  = {axi_addr_width};")
    sv.append(f"  localparam int unsigned LingoAxilAddrWidth = {axil_addr_width};")
    sv.append(f"  localparam int unsigned LingoNumBanks      = {n_banks};")
    sv.append(f"  localparam int unsigned LingoBankBytes     = {bank_bytes};")
    sv.append(f"  localparam int unsigned LingoSpadBytes     = {spad_bytes};")
    sv.append(f"  localparam int unsigned LingoCfgBytes      = {cfg_bytes};")
    sv.append(f"  localparam int unsigned LingoSpmBytes      = {spm_bytes};")
    sv.append(f"  localparam int unsigned LingoCfgBase       = 'h{cfg_base:x};")
    sv.append(f"  localparam int unsigned LingoTileNum       = {tile_num};")
    sv.append("  // --- SoC address map (integration contract) ---")
    sv.append(f"  localparam longint unsigned SocSpmCachedBase   = 64'h{SOC_SPM_CACHED_BASE:08x};")
    sv.append(f"  localparam longint unsigned SocSpmUncachedBase = 64'h{SOC_SPM_UNCACHED_BASE:08x};")
    sv.append(f"  localparam longint unsigned SocCsrBase         = 64'h{SOC_CSR_BASE:08x};")
    sv.append(f"  localparam longint unsigned SocSpmRegionBytes  = {spm_region};")
    sv.append(f"  localparam longint unsigned SocCsrRegionBytes  = {SOC_CSR_REGION_BYTES};")
    sv.append("endpackage")
    (SOC_DIR / "src/lingo_soc_pkg.sv").write_text("\n".join(sv) + "\n")

    c = [HEADER_C, "#ifndef LINGO_REGS_H", "#define LINGO_REGS_H", ""]
    c.append(f"#define LINGO_SPM_BASE         0x{SOC_SPM_UNCACHED_BASE:08X}u  /* uncached alias */")
    c.append(f"#define LINGO_SPM_CACHED_BASE  0x{SOC_SPM_CACHED_BASE:08X}u")
    c.append(f"#define LINGO_CSR_BASE         0x{SOC_CSR_BASE:08X}u")
    c.append(f"#define LINGO_SPM_BYTES        0x{spm_bytes:X}u")
    c.append(f"#define LINGO_SPAD_BYTES       0x{spad_bytes:X}u")
    c.append(f"#define LINGO_CFG_BYTES        0x{cfg_bytes:X}u")
    c.append(f"#define LINGO_CFG_BASE         0x{cfg_base:X}u  /* SPM offset of the config stream */")
    c.append(f"#define LINGO_NUM_BANKS        {n_banks}u")
    c.append(f"#define LINGO_TILE_NUM         {tile_num}u")
    c.append("")
    for name, off in regs:
        c.append(f"#define LINGO_{name.upper():24s} 0x{off:02X}u")
    c.append("")
    c.append("#endif /* LINGO_REGS_H */")
    (SOC_DIR / "sw/include").mkdir(parents=True, exist_ok=True)
    (SOC_DIR / "sw/include/lingo_regs.h").write_text("\n".join(c) + "\n")

    print(f"lingo_soc_pkg.sv: axi {data_width}b/{id_width}b id/{axi_addr_width}b addr, "
          f"axilite {axil_addr_width}b, SPM {spm_bytes} B ({n_banks} banks + cfg)")
    print(f"lingo_regs.h: {len(regs)} registers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
