#!/usr/bin/env python3
"""Generate a C header with a kernel's LinGo configuration for the SoC tests.

Reads a mapper output directory (e.g. ../benchmarks/gemm):
    config.bit            text bitstream: "<addr> <data>" hex per line
    <kernel>_cocotb.py    mapper-generated host module (IOB/TILE enables,
                          SPM buffer offsets and sizes)

Output:
    sw/tests/lingo_<kernel>_cfg.h

Usage:
    python3 util/gen_lingo_cfg.py gemm [benchmark_dir]
"""

import re
import sys
from pathlib import Path

SOC_DIR = Path(__file__).resolve().parent.parent

HEADER_C = """/* GENERATED by util/gen_lingo_cfg.py from {src} -- do not edit. */"""


def parse_config_bit(path: Path):
    """Return a flat list of 16-bit halfwords [data_lo, data_hi, addr] per row,
    matching the layout the LinGo runtime streams into the config SPM."""
    halfwords = []
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        m = re.fullmatch(r"([0-9a-fA-F]+)\s+([0-9a-fA-F]+)", line)
        if not m:
            raise ValueError(f"{path}:{lineno}: malformed line {line!r}")
        addr, data = int(m.group(1), 16), int(m.group(2), 16)
        if addr > 0xFFFF or data > 0xFFFFFFFF:
            raise ValueError(f"{path}:{lineno}: value out of range")
        halfwords += [data & 0xFFFF, data >> 16, addr]
    return halfwords


def parse_cocotb(path: Path):
    """Extract IOB_ENABLE / TILE_ENABLE and the SPM buffer layout."""
    text = path.read_text()

    def get_list(name):
        m = re.search(rf"^{name}\s*=\s*\[([^\]]*)\]", text, re.M)
        if not m:
            raise ValueError(f"{path}: {name} not found")
        return [int(x.strip(), 0) for x in m.group(1).split(",") if x.strip()]

    iob_en = get_list("IOB_ENABLE")
    tile_en = get_list("TILE_ENABLE")

    # DeviceData(0x6000, 256) entries, input block first, then outputs
    blocks = []
    for m in re.finditer(r"(iptrs|optrs)\s*=\s*\[(.*?)\]", text, re.S):
        entries = re.findall(r"DeviceData\((0x[0-9a-fA-F]+|\d+),\s*(\d+)\)", m.group(2))
        blocks.append([(int(a, 0), int(s)) for a, s in entries])
    if len(blocks) != 2:
        raise ValueError(f"{path}: could not find iptrs/optrs DeviceData lists")
    return iob_en, tile_en, blocks[0], blocks[1]


def le_word(byte_list):
    """Little-endian bytes -> one 32-bit word."""
    return sum(b << (8 * i) for i, b in enumerate(byte_list))


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    kernel = sys.argv[1]
    bench = Path(sys.argv[2]) if len(sys.argv) > 2 else SOC_DIR.parent / "benchmarks" / kernel

    halfwords = parse_config_bit(bench / "config.bit")
    iob_en, tile_en, inputs, outputs = parse_cocotb(bench / f"{kernel}_cocotb.py")
    cfg_num = len(halfwords) // 3

    guard = f"LINGO_{kernel.upper()}_CFG_H"
    k = kernel.upper()
    c = [HEADER_C.format(src=f"benchmarks/{kernel}"), f"#ifndef {guard}",
         f"#define {guard}", "", "#include <stdint.h>", ""]
    c.append(f"#define LINGO_{k}_CFG_NUM   {cfg_num}u   /* 3-halfword rows */")
    c.append(f"#define LINGO_{k}_IOB_ENS   0x{le_word(iob_en):X}u")
    c.append(f"#define LINGO_{k}_TILE_ENS  0x{le_word(tile_en):X}u")
    c.append("")
    c.append(f"/* SPM buffer layout: inputs (incl. output-initializer), then outputs */")
    c.append(f"static const uint32_t lingo_{kernel}_in_off[] = {{")
    c.append("    " + ", ".join(f"0x{a:X}u" for a, _ in inputs))
    c.append("};")
    c.append(f"static const uint32_t lingo_{kernel}_in_size[] = {{")
    c.append("    " + ", ".join(f"{s}u" for _, s in inputs))
    c.append("};")
    c.append(f"static const uint32_t lingo_{kernel}_out_off[] = {{")
    c.append("    " + ", ".join(f"0x{a:X}u" for a, _ in outputs))
    c.append("};")
    c.append(f"static const uint32_t lingo_{kernel}_out_size[] = {{")
    c.append("    " + ", ".join(f"{s}u" for _, s in outputs))
    c.append("};")
    c.append("")
    c.append(f"/* Config stream: {cfg_num} rows x [data_lo, data_hi, addr], 16-bit */")
    c.append(f"static const uint16_t lingo_{kernel}_cfg[] = {{")
    for i in range(0, len(halfwords), 12):
        c.append("    " + ", ".join(f"0x{w:04X}" for w in halfwords[i:i + 12]) + ",")
    c.append("};")
    c.append("")
    c.append(f"#endif /* {guard} */")

    out = SOC_DIR / "sw/tests" / f"lingo_{kernel}_cfg.h"
    out.write_text("\n".join(c) + "\n")
    print(f"{out}: {cfg_num} config rows, iob_en=0x{le_word(iob_en):X}, "
          f"tile_en=0x{le_word(tile_en):X}, {len(inputs)} in / {len(outputs)} out buffers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
